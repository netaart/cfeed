export type Lang = 'zh' | 'en'
const dicts: Record<Lang, Record<Key, string>> = { zh, en }

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: Key) => string }
const I18n = createContext<Ctx | null>(null)

function initialLang(): Lang {
  const saved = localStorage.getItem('cfeed.lang')
  if (saved === 'zh' || saved === 'en') return saved
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang)
  const setLang = (l: Lang) => {
    localStorage.setItem('cfeed.lang', l)
    document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en'
    setLangState(l)
  }
  return <I18n.Provider value={{ lang, setLang, t: (k) => dicts[lang][k] }}>{children}</I18n.Provider>
}

export function useT() {
  const ctx = useContext(I18n)
  if (!ctx) throw new Error('useT must be used inside I18nProvider')
  return ctx
}
